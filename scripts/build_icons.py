"""画面のアイコンの SVG スプライト（src/docseed/web/static/icons.svg）を作る。docs/design/extensions.md 3.2。

Material Symbols（Apache-2.0）の Sharp・太さ 400・塗りなしの SVG を npm の @material-symbols/svg-400
（版を固定）から取り、icons.txt に書いたものだけを <symbol id="i-<名前>"> にまとめる。
アイコンを足すときだけ開発者が実行する（実行時には作らない）。

    python scripts/build_icons.py              # npm の registry から取得
    python scripts/build_icons.py --src DIR    # 展開済みのパッケージ（package/ の中）を使う
    python scripts/build_icons.py --check      # icons.txt と icons.svg が合っているか（CI 用。通信しない）
"""

from __future__ import annotations

import argparse
import io
import re
import sys
import tarfile
import urllib.request
from pathlib import Path

PACKAGE = "@material-symbols/svg-400"
VERSION = "0.48.3"
STYLE = "sharp"
ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "src" / "docseed" / "web"
LIST = WEB / "icons.txt"
OUT = WEB / "static" / "icons.svg"
LICENSE_OUT = WEB / "static" / "LICENSE-material-symbols.txt"
TARBALL = f"https://registry.npmjs.org/{PACKAGE}/-/svg-400-{VERSION}.tgz"


def names() -> list[str]:
    out = []
    for line in LIST.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line and line not in out:
            out.append(line)
    return out


def sprite_names(text: str) -> list[str]:
    return re.findall(r'<symbol id="i-([a-z0-9_]+)"', text)


def _load(src: Path | None) -> tuple[dict[str, str], str]:
    """{名前: SVG の中身} とライセンスの文面。"""
    if src is not None:
        files = {p.stem: p.read_text() for p in (src / STYLE).glob("*.svg")}
        return files, (src / "LICENSE").read_text()
    with urllib.request.urlopen(TARBALL, timeout=60) as r:
        data = r.read()
    files, lic = {}, ""
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
        for m in tar.getmembers():
            if m.name.startswith(f"package/{STYLE}/") and m.name.endswith(".svg"):
                files[Path(m.name).stem] = tar.extractfile(m).read().decode()
            elif m.name == "package/LICENSE":
                lic = tar.extractfile(m).read().decode()
    return files, lic


def build(src: Path | None) -> None:
    files, lic = _load(src)
    parts = []
    missing = []
    for n in names():
        svg = files.get(n)
        if svg is None:
            missing.append(n)
            continue
        vb = re.search(r'viewBox="([^"]+)"', svg).group(1)
        inner = re.sub(r"^.*?<svg[^>]*>|</svg>\s*$", "", svg.strip(), flags=re.S)
        parts.append(f'<symbol id="i-{n}" viewBox="{vb}">{inner}</symbol>')
    if missing:
        sys.exit("見つからないアイコン: " + ", ".join(missing))
    head = (f"<!-- Material Symbols {STYLE} (weight 400) from {PACKAGE}@{VERSION}. Apache-2.0: "
            "LICENSE-material-symbols.txt. Generated by scripts/build_icons.py; do not edit. -->\n")
    OUT.write_text(head + '<svg xmlns="http://www.w3.org/2000/svg">\n' + "\n".join(parts) + "\n</svg>\n")
    LICENSE_OUT.write_text(lic)
    print(f"{OUT.relative_to(ROOT)}: {len(parts)} 個")


def check() -> int:
    want = names()
    got = sprite_names(OUT.read_text()) if OUT.exists() else []
    if want != got:
        print(f"icons.txt と icons.svg が合っていません。python scripts/build_icons.py を実行してください\n"
              f"  足りない: {sorted(set(want) - set(got))}\n  余分: {sorted(set(got) - set(want))}")
        return 1
    return 0


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--src", type=Path, help="展開済みの npm パッケージ（package/）")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.check:
        sys.exit(check())
    build(a.src)


if __name__ == "__main__":
    main()
